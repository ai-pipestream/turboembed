//! Shared ISO 3166-1 alpha-2 country table mapping each region to:
//! 1. Its primary `number_notation` ([`NumberNotation`]) from the country's
//!    native locale (`fr-FR`, `es-ES`, `it-IT`, `de-DE`, `pt-PT`, `el-GR`,
//!    `ru-RU`, `nl-NL`, etc.) for [`crate::NumberScanner::for_region`],
//!    [`crate::QuantityExtractor::for_region`],
//!    [`super::RegionAwareNumberAnnotator`], and
//!    [`super::RegionAwareQuantityAnnotator`].
//! 2. Its `money_notation` and single-code-point `Sc` `(symbol, currency)`
//!    override as OpenNLP's `RegionAwareMoneyAnnotator.localeOf` resolves them
//!    on the pinned JDK 21 runtime (`Temurin-21.0.12.1+1`). Because
//!    `Locale.getAvailableLocales()` lists `en-<CC>` before native locales in
//!    several European countries (`FR`, `ES`, `IT`, `PT`, `GR`, etc.),
//!    `RegionAwareMoneyAnnotator` resolves `€` -> `EUR` on the `en-<CC>` locale
//!    with `LatinUs`, whereas the country's own number notation is `LatinEu`.
//!    Keeping both columns preserves 100% JVM parity on
//!    [`crate::MoneyExtractor::for_region`] while giving regional number and
//!    quantity extraction the country's true [`NumberNotation`].

use turbo_analysis_layers::{Currency, NumberNotation};

/// A currency code from a literal the table knows to be well formed.
const fn code(c: &[u8; 3]) -> Currency {
    match Currency::new(*c) {
        Some(c) => c,
        None => panic!("a code of three ASCII capital letters"),
    }
}

/// `(country_code, number_notation, money_notation, optional_money_symbol_override)`.
