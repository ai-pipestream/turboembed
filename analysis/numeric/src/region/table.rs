//! Shared ISO 3166-1 alpha-2 country table mapping each region to its
//! [`NumberNotation`] and, where `RegionAwareMoneyAnnotator.localeOf` on the
//! pinned JDK 21 runtime (`Temurin-21.0.12.1+1`) resolves a single-code-point
//! `Sc` currency symbol, its `(symbol, currency)` override.

use turbo_analysis_layers::{Currency, NumberNotation};

/// A currency code from a literal the table knows to be well formed.
const fn code(c: &[u8; 3]) -> Currency {
    match Currency::new(*c) {
        Some(c) => c,
        None => panic!("a code of three ASCII capital letters"),
    }
}

