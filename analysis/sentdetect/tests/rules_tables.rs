//! The rule splitter's data tables (`src/rules/tables.rs`) are exactly
//! what this file renders from the sources in `data/rules`.
//!
//! The sources are kept as they were published: the CLDR segmentation
//! files and the sentencex word lists. To change the data, change a
//! source file (or this renderer) and run
//!
//! ```text
//! TURBO_WRITE_RULE_TABLES=1 cargo test -p turbo-sentdetect --test rules_tables
//! ```
//!
//! which writes the tables, then run the test again without the variable.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The CLDR files, by language.
const CLDR: [&str; 7] = ["de", "en", "es", "fr", "it", "pt", "ru"];

/// The sentencex abbreviation lists, by language.
const SENTENCEX: [&str; 7] = ["am", "ar", "bg", "da", "kk", "pl", "uk"];

fn data() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("data/rules")
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

/// The `<suppression>` entries of a CLDR segmentation file, with the XML
/// character references the files use resolved. Returns the entries and
/// the number left out because they do not end with a full stop, which a
/// suppression ending at a terminator always does.
fn cldr_suppressions(text: &str) -> (Vec<String>, usize) {
    let mut out = Vec::new();
    let mut unstopped = 0;
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("<suppression>") else { continue };
        let entry = rest.strip_suffix("</suppression>").expect("one suppression per line");
        const REFERENCES: [&str; 5] = ["&apos;", "&quot;", "&lt;", "&gt;", "&amp;"];
        for (at, _) in entry.match_indices('&') {
            assert!(REFERENCES.iter().any(|r| entry[at..].starts_with(r)), "an unknown reference in {entry}");
        }
        let entry = entry
            .replace("&apos;", "'")
            .replace("&quot;", "\"")
            .replace("&lt;", "<")
            .replace("&gt;", ">")
            .replace("&amp;", "&");
        if entry.ends_with('.') {
            out.push(entry);
        } else {
            unstopped += 1;
        }
    }
    out.sort();
    out.dedup();
    (out, unstopped)
}

/// A sentencex word list: one entry per line, lines starting with `//`
/// are comments, entries are trimmed. Returns the entries and the number
/// left out because they hold whitespace, which a single word never does.
fn sentencex_words(text: &str, lower: bool) -> (Vec<String>, usize) {
    let mut out = Vec::new();
    let mut spaced = 0;
    for line in text.lines() {
        let entry = line.trim();
        if entry.is_empty() || entry.starts_with("//") {
            continue;
        }
        if entry.chars().any(char::is_whitespace) {
            spaced += 1;
            continue;
        }
        let entry = if lower { entry.to_lowercase() } else { entry.to_owned() };
        // The splitter looks up the word without its final full stop; a
        // few entries were written with it.
        let entry = entry.strip_suffix('.').unwrap_or(&entry).to_owned();
        if !entry.is_empty() {
            out.push(entry);
        }
    }
    out.sort();
    out.dedup();
    (out, spaced)
}

fn emit(out: &mut String, doc: &str, name: &str, entries: &[String]) {
    writeln!(out).unwrap();
    for line in doc.lines() {
        writeln!(out, "/// {line}").unwrap();
    }
    writeln!(out, "pub(crate) const {name}: &[&str] = &[").unwrap();
    for e in entries {
        writeln!(out, "    {e:?},").unwrap();
    }
    writeln!(out, "];").unwrap();
}

fn render() -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by analysis/sentdetect/tests/rules_tables.rs from the files in\n\
         // analysis/sentdetect/data/rules. Do not edit this file by hand: change a\n\
         // source file and run that test with TURBO_WRITE_RULE_TABLES=1.\n\
         //\n\
         // CLDR data: Copyright 2004-2026 Unicode, Inc., Unicode License v3\n\
         // (data/rules/cldr/LICENSE). sentencex data: Copyright 2025 Santhosh\n\
         // Thottingal, MIT License (data/rules/sentencex/LICENSE).\n",
    );
    for lang in CLDR {
        let (entries, unstopped) = cldr_suppressions(&read(&data().join(format!("cldr/{lang}.xml"))));
        assert!(!entries.is_empty(), "{lang}");
        emit(
            &mut out,
            &format!(
                "The CLDR 48.2 sentence break suppressions of `{lang}`, {} entries{}.",
                entries.len(),
                match unstopped {
                    0 => String::new(),
                    n => format!("; {n} without a final full stop are left out"),
                }
            ),
            &format!("CLDR_{}", lang.to_uppercase()),
            &entries,
        );
    }
    for lang in SENTENCEX {
        let (entries, spaced) = sentencex_words(&read(&data().join(format!("sentencex/abbrev/{lang}.txt"))), true);
        let doc = format!(
            "The sentencex abbreviations of `{lang}` in lower case, {} entries{}.",
            entries.len(),
            match spaced {
                0 => String::new(),
                n => format!("; {n} holding a space are left out"),
            }
        );
        emit(&mut out, &doc, &format!("SENTENCEX_{}", lang.to_uppercase()), &entries);
    }
    let (starters, spaced) = sentencex_words(&read(&data().join("sentencex/starters/en.txt")), false);
    assert_eq!(spaced, 0);
    emit(
        &mut out,
        &format!("The sentencex sentence starters of `en`, {} entries.", starters.len()),
        "SENTENCEX_STARTERS_EN",
        &starters,
    );
    out
}

#[test]
fn tables_match_their_sources() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/rules/tables.rs");
    let fresh = render();
    if std::env::var_os("TURBO_WRITE_RULE_TABLES").is_some() {
        std::fs::write(&path, &fresh).unwrap();
    }
    let committed = read(&path);
    assert!(committed == fresh, "src/rules/tables.rs differs from its sources; see this file's comment");
}

#[test]
fn renderer_reads_the_formats() {
    let xml = "<suppressions>\n  <suppression>Mr.</suppression>\n  <suppression>A&amp;B.</suppression>\n  \
               <suppression>Mr.</suppression>\n  <suppression>A.M</suppression>\n</suppressions>\n";
    assert_eq!(cldr_suppressions(xml), (vec!["A&B.".to_owned(), "Mr.".to_owned()], 1));
    let list = "// comment\n  Abc \n\nx.y.\nا. د\nabc\n";
    assert_eq!(sentencex_words(list, true), (vec!["abc".to_owned(), "x.y".to_owned()], 1));
    assert_eq!(sentencex_words(list, false).0, ["Abc", "abc", "x.y"]);
}
