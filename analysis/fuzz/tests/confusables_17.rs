//! The confusable mappings that changed after Unicode 17.0.0
//! (`src/runs/confusables_17.rs`) are exactly what this file renders from
//! two releases of confusables.txt: 17.0.0, kept in `data/unicode-17.0.0`,
//! and the release `turbo-unicode` is generated from, in
//! `analysis/unicode/ucd`.
//!
//! To change the table, change a data file (or this renderer) and run
//!
//! ```text
//! TURBO_WRITE_CONFUSABLES_17=1 cargo test -p turbo-fuzz --test confusables_17
//! ```
//!
//! which writes the table, then run the test again without the variable.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// The widest line rustfmt leaves alone (`max_width` in rustfmt.toml).
const MAX_WIDTH: usize = 120;

/// One release of confusables.txt: its version and the prototype of each
/// source code point.
#[derive(Debug, PartialEq)]
struct Release {
    version: String,
    prototypes: BTreeMap<u32, String>,
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn code_point(hex: &str, line: usize) -> char {
    let digits = (4..=6).contains(&hex.len()) && hex.bytes().all(|b| b.is_ascii_hexdigit());
    let scalar = u32::from_str_radix(hex, 16).ok().filter(|_| digits).and_then(char::from_u32);
    scalar.unwrap_or_else(|| panic!("line {line}: `{hex}` is not a code point"))
}

/// Reads confusables.txt: a `# Version: X.Y.Z` comment, and data lines of
/// the form `source ; target ; MA`, the target one or more code points.
/// Whatever follows a `#` is a comment. A line of any other form stops the
/// renderer, with its number.
fn parse(text: &str) -> Release {
    let text = text.strip_prefix('\u{FEFF}').unwrap_or(text);
    let mut version = None;
    let mut prototypes = BTreeMap::new();
    for (line, content) in text.lines().enumerate().map(|(i, content)| (i + 1, content)) {
        if let Some(found) = content.strip_prefix("# Version:") {
            assert!(version.replace(found.trim().to_owned()).is_none(), "line {line}: a second version");
        }
        let data = content.split_once('#').map_or(content, |(data, _)| data).trim();
        if data.is_empty() {
            continue;
        }
        let fields: Vec<&str> = data.split(';').map(str::trim).collect();
        let [source, target, "MA"] = fields[..] else { panic!("line {line}: expected `source ; target ; MA`") };
        let target: String = target.split_whitespace().map(|hex| code_point(hex, line)).collect();
        assert!(!target.is_empty(), "line {line}: an empty target");
        let known = prototypes.insert(code_point(source, line) as u32, target);
        assert!(known.is_none(), "line {line}: the source is listed twice");
    }
    let version = version.expect("a `# Version:` line");
    assert!(!prototypes.is_empty(), "confusables.txt {version} holds no mapping");
    Release { version, prototypes }
}

/// Each source code point whose prototype in `old` is not its prototype in
/// `new`, in code point order, with the one `old` gives it: `None` where
/// only `new` maps it.
fn changes<'a>(old: &'a Release, new: &Release) -> Vec<(u32, Option<&'a str>)> {
    let mut sources: Vec<u32> = old.prototypes.keys().chain(new.prototypes.keys()).copied().collect();
    sources.sort_unstable();
    sources.dedup();
    let differs = |cp: &u32| old.prototypes.get(cp) != new.prototypes.get(cp);
    sources.into_iter().filter(differs).map(|cp| (cp, old.prototypes.get(&cp).map(String::as_str))).collect()
}

/// The table file: the changes from `old` to `new`, every character of a
/// prototype as a `\u{...}` escape, so the file is plain ASCII.
fn render(old: &Release, new: &Release) -> String {
    let (was, now) = (&old.version, &new.version);
    let mut out = format!(
        "//! Generated by analysis/fuzz/tests/confusables_17.rs from confusables.txt\n\
         //! {was} (analysis/fuzz/data/unicode-{was}) and {now}\n\
         //! (analysis/unicode/ucd). Do not edit this file by hand: change a data\n\
         //! file and run that test with TURBO_WRITE_CONFUSABLES_17=1.\n\
         //!\n\
         //! The confusable mappings of confusables.txt {was}, the data OpenNLP\n\
         //! bundles, where they differ from the {now} data `turbo_unicode` has:\n\
         //! each source code point whose {was} prototype is not its {now} one,\n\
         //! with the {was} prototype, or `None` where {was} maps it to nothing.\n\
         //! Sorted by code point. Unicode data, used under the Unicode License v3\n\
         //! (analysis/fuzz/data/unicode-{was}/LICENSE).\n\
         \n\
         pub(crate) static CHANGES_17: &[(u32, Option<&str>)] = &[\n"
    );
    for (cp, prototype) in changes(old, new) {
        let entry = match prototype {
            Some(target) => {
                let escapes: String = target.chars().map(|c| format!("\\u{{{:X}}}", c as u32)).collect();
                format!("    (0x{cp:04X}, Some(\"{escapes}\")),")
            }
            None => format!("    (0x{cp:04X}, None),"),
        };
        assert!(entry.len() <= MAX_WIDTH, "U+{cp:04X}: rustfmt would wrap an entry of {} columns", entry.len());
        writeln!(out, "{entry}").unwrap();
    }
    out.push_str("];\n");
    out
}

#[test]
fn the_table_is_what_the_two_releases_give() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let old = parse(&read(&manifest.join("data/unicode-17.0.0/confusables.txt")));
    let new = parse(&read(&manifest.join("../unicode/ucd/confusables.txt")));
    assert_eq!(old.version, "17.0.0", "the directory names the release it holds");
    let (major, minor, update) = turbo_unicode::UNICODE_VERSION;
    assert_eq!(new.version, format!("{major}.{minor}.{update}"), "the release turbo-unicode is generated from");
    let fresh = render(&old, &new);
    let path = manifest.join("src/runs/confusables_17.rs");
    if std::env::var_os("TURBO_WRITE_CONFUSABLES_17").is_some() {
        std::fs::write(&path, &fresh).unwrap();
    }
    assert!(read(&path) == fresh, "src/runs/confusables_17.rs differs from its sources; see this file's comment");
}

/// A release of `version` holding `lines`, as the file writes one.
fn release(version: &str, lines: &str) -> Release {
    parse(&format!("\u{FEFF}# confusables.txt\n# Version: {version}\n\n{lines}"))
}

#[test]
fn the_renderer_reads_the_format() {
    let read = release(
        "17.0.0",
        "05AD ;\t0596 ;\tMA\t# ( ֭ → ֖ ) HEBREW ACCENT DEHI → HEBREW ACCENT TIPEHA\t# \n\
         \n\
         # total: 1\n\
         1F74C ;\t0043 0326 ;\tMA\t#* ( 🝌 → C̦ ) ALCHEMICAL SYMBOL → C, COMBINING COMMA BELOW\n\
         0025 ; 00BA 002F 2080 ; MA\n",
    );
    let prototypes = BTreeMap::from([
        (0x25, "\u{BA}/\u{2080}".to_owned()),
        (0x5AD, "\u{596}".to_owned()),
        (0x1F74C, "C\u{326}".to_owned()),
    ]);
    assert_eq!(read, Release { version: "17.0.0".to_owned(), prototypes });
}

#[test]
fn the_table_holds_the_old_prototype_of_each_changed_source() {
    let old = release("17.0.0", "0041 ; 0410 ; MA\n0042 ; 0412 ; MA\n0043 ; 0421 ; MA\n10000 ; 0044 0326 ; MA\n");
    // U+0041 keeps its prototype, U+0042 gets another, U+0043 loses its
    // mapping, U+0045 gains one, and U+10000 loses half of its target.
    let new = release("18.0.0", "0041 ; 0410 ; MA\n0042 ; 0432 ; MA\n0045 ; 0415 ; MA\n10000 ; 0044 ; MA\n");
    assert_eq!(
        changes(&old, &new),
        [(0x42, Some("\u{412}")), (0x43, Some("\u{421}")), (0x45, None), (0x10000, Some("D\u{326}"))]
    );
    assert!(changes(&old, &old).is_empty());
    let table = render(&old, &new);
    assert!(
        table.starts_with("//! Generated by analysis/fuzz/tests/confusables_17.rs from confusables.txt\n//! 17.0.0 ")
    );
    assert!(table.is_ascii());
    let entries = "pub(crate) static CHANGES_17: &[(u32, Option<&str>)] = &[\n    \
                   (0x0042, Some(\"\\u{412}\")),\n    \
                   (0x0043, Some(\"\\u{421}\")),\n    \
                   (0x0045, None),\n    \
                   (0x10000, Some(\"\\u{44}\\u{326}\")),\n\
                   ];\n";
    assert!(table.ends_with(entries), "{table}");
}

#[test]
#[should_panic(expected = "line 4: expected `source ; target ; MA`")]
fn a_line_of_another_form_stops_the_renderer() {
    release("17.0.0", "0041 ; 0410 ; SL\n");
}

#[test]
#[should_panic(expected = "line 5: the source is listed twice")]
fn a_source_listed_twice_stops_the_renderer() {
    release("17.0.0", "0041 ; 0410 ; MA\n0041 ; 0412 ; MA\n");
}

#[test]
#[should_panic(expected = "line 4: `110000` is not a code point")]
fn a_number_past_the_code_space_stops_the_renderer() {
    release("17.0.0", "0041 ; 110000 ; MA\n");
}
