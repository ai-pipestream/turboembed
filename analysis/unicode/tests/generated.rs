//! The committed tables are exactly what the generator writes from ucd/.

use std::fs;
use std::path::PathBuf;

mod common;

#[test]
fn committed_tables_match_the_generator_output() {
    let out = std::env::temp_dir().join(format!("turbo-unicode-tables-{}", std::process::id()));
    let files = turbo_unicode_gen::generate(&common::ucd_dir(), &out).expect("the generator writes its files");
    let committed = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src").join("tables");
    for file in &files {
        let fresh = fs::read(out.join(file.name)).expect("the generated file exists");
        let current = fs::read(committed.join(file.name)).unwrap_or_default();
        assert!(fresh == current, "src/tables/{} differs from the generator output; run the generator", file.name);
    }
    let mut names: Vec<String> = fs::read_dir(&committed)
        .expect("src/tables exists")
        .map(|entry| entry.expect("a directory entry").file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();
    let mut expected: Vec<String> = files.iter().map(|file| file.name.to_owned()).collect();
    expected.sort();
    assert_eq!(names, expected, "src/tables holds exactly the generated files");
    fs::remove_dir_all(&out).expect("the temporary directory is removed");
}

#[test]
fn generator_output_is_deterministic() {
    let first = turbo_unicode_gen::render(&common::ucd_dir());
    let second = turbo_unicode_gen::render(&common::ucd_dir());
    assert_eq!(first.len(), second.len());
    for (a, b) in first.iter().zip(&second) {
        assert_eq!(a.name, b.name);
        assert!(a.contents == b.contents, "{} differs between two runs", a.name);
    }
}

#[test]
fn generated_files_carry_the_notice_and_the_version() {
    let (major, minor, update) = turbo_unicode::UNICODE_VERSION;
    let version = format!("Unicode {major}.{minor}.{update}");
    for file in turbo_unicode_gen::render(&common::ucd_dir()) {
        let head: String =
            file.contents.lines().take(5).map(|line| line.trim_start_matches("// ")).collect::<Vec<_>>().join(" ");
        assert!(head.starts_with("Generated by turbo-unicode-gen from "), "{}", file.name);
        assert!(head.contains(&version), "{} does not name {version}", file.name);
        assert!(head.contains("Do not edit this file by hand"), "{}", file.name);
        assert!(file.contents.is_ascii(), "{} is plain ASCII", file.name);
        assert!(file.contents.len() < 2 * 1024 * 1024, "{} is below 2 MB", file.name);
    }
}
