import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Random;

import opennlp.spellcheck.SuggestItem;
import opennlp.spellcheck.Verbosity;
import opennlp.spellcheck.dictionary.SymSpellModel;
import opennlp.spellcheck.dictionary.SymSpellModelSerializer;
import opennlp.spellcheck.distance.LevenshteinDistance;
import opennlp.spellcheck.normalizer.SpellCheckingCharSequenceNormalizer;
import opennlp.spellcheck.symspell.SymSpell;
import opennlp.spellcheck.symspell.SymSpellConfig;
import opennlp.tools.util.normalizer.UnicodeWhitespace;

/**
 * Writes the SymSpell test data of turbo-normalize: two models serialized by
 * OpenNLP's SymSpellModelSerializer, and the results OpenNLP gives for
 * lookups, compound lookups and the spell checking normalizer over generated
 * inputs. Run with the directory holding the two tiny frequency dictionaries
 * as the only argument; the files are written there. The inputs come from a
 * seeded java.util.Random, so a run reproduces the same files.
 */
public final class GenerateSpellcheckData {

  private static final String LETTERS = "abcdefghijklmnopqrstuvwxyz";

  private GenerateSpellcheckData() {
  }

  public static void main(String[] args) throws IOException {
    final Path dir = Path.of(args[0]);
    final Map<String, Long> unigrams = readColumns(dir.resolve("frequency_dictionary_tiny.txt"), 1);
    final Map<String, Long> bigrams = readColumns(dir.resolve("frequency_bigramdictionary_tiny.txt"), 2);

    // Model A: the tiny dictionaries and a few entries that exercise the
    // string and count encodings (U+0000, a supplementary character, an
    // accent, the largest count).
    final Map<String, Long> unigramsA = new LinkedHashMap<>(unigrams);
    unigramsA.put("café", 4242L);
    unigramsA.put("a\u0000b", 7L);
    unigramsA.put("𐐨word", 1000L);
    unigramsA.put("maximum", Long.MAX_VALUE);
    final SymSpellModel a = new SymSpellModel("en", "spellcheck-tiny", "1.0",
        SymSpellConfig.defaultConfig(), unigramsA, bigrams);

    // Model B: Levenshtein, a smaller index, a count threshold that leaves
    // two words unindexed, and a fixed corpus size.
    final Map<String, Long> unigramsB = new LinkedHashMap<>();
    unigramsB.put("bank", 100L);
    unigramsB.put("band", 90L);
    unigramsB.put("bonk", 2L);
    unigramsB.put("banker", 40L);
    unigramsB.put("bandana", 1L);
    unigramsB.put("bandanas", 3L);
    unigramsB.put("the", 5000L);
    unigramsB.put("riverbank", 12L);
    final Map<String, Long> bigramsB = new LinkedHashMap<>();
    bigramsB.put("river bank", 30L);
    bigramsB.put("the bank", 300L);
    final SymSpellConfig configB = SymSpellConfig.builder()
        .maxDictionaryEditDistance(1)
        .prefixLength(4)
        .countThreshold(3)
        .editDistance(LevenshteinDistance.INSTANCE)
        .corpusWordCount(1_000_000_000L)
        .build();
    final SymSpellModel b = new SymSpellModel("de", "spellcheck-levenshtein", "2.5", configB,
        unigramsB, bigramsB);

    Files.write(dir.resolve("model-tiny.bin"), serialize(a));
    Files.write(dir.resolve("model-levenshtein.bin"), serialize(b));

    try (PrintWriter out = new PrintWriter(Files.newBufferedWriter(
        dir.resolve("expected.txt"), StandardCharsets.UTF_8))) {
      out.print("# Generated by GenerateSpellcheckData.java; see README.md.\n");
      final Random random = new Random(189);
      final List<String> words = new ArrayList<>(unigrams.keySet());
      writeLookups(out, "tiny", a.getSymSpell(), terms(random, words, unigramsA.keySet()), 2);
      writeLookups(out, "levenshtein", b.getSymSpell(), terms(random,
          new ArrayList<>(unigramsB.keySet()), unigramsB.keySet()), 1);
      final List<String> sentences = sentences(random, words);
      writeCompound(out, "tiny", a.getSymSpell(), sentences, 2);
      writeCompound(out, "levenshtein", b.getSymSpell(),
          sentences(random, new ArrayList<>(unigramsB.keySet())), 1);
      writeNormalizer(out, a.getSymSpell(), sentences, casedSentences(random, words));
    }
  }

  private static Map<String, Long> readColumns(Path file, int wordColumns) throws IOException {
    final Map<String, Long> map = new LinkedHashMap<>();
    for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
      final String[] columns = line.trim().split("[ \t]+");
      final String key = wordColumns == 1 ? columns[0] : columns[0] + " " + columns[1];
      map.merge(key, Long.parseLong(columns[wordColumns]), Long::sum);
    }
    return map;
  }

  private static byte[] serialize(SymSpellModel model) throws IOException {
    final ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    new SymSpellModelSerializer().serialize(model, bytes);
    return bytes.toByteArray();
  }

  /** Every dictionary word, and three edits of each of them. */
  private static List<String> terms(Random random, List<String> words, Iterable<String> all) {
    final List<String> terms = new ArrayList<>();
    for (String word : all) {
      terms.add(word);
    }
    terms.add("");
    for (String word : words) {
      for (int k = 0; k < 3; k++) {
        terms.add(mutate(random, word, 1 + random.nextInt(3)));
      }
    }
    return terms;
  }

  /** Applies {@code edits} random deletions, insertions, substitutions or transpositions. */
  private static String mutate(Random random, String word, int edits) {
    final StringBuilder s = new StringBuilder(word);
    for (int e = 0; e < edits; e++) {
      final int kind = random.nextInt(4);
      final int at = s.length() == 0 ? 0 : random.nextInt(s.length());
      final char letter = LETTERS.charAt(random.nextInt(LETTERS.length()));
      if (kind == 0 && s.length() > 1) {
        s.deleteCharAt(at);
      } else if (kind == 1 || s.length() == 0) {
        s.insert(at, letter);
      } else if (kind == 2) {
        s.setCharAt(at, letter);
      } else if (at + 1 < s.length()) {
        final char c = s.charAt(at);
        s.setCharAt(at, s.charAt(at + 1));
        s.setCharAt(at + 1, c);
      }
    }
    return s.toString();
  }

  /** Phrases of two to five words, some misspelled, some run together, some split. */
  private static List<String> sentences(Random random, List<String> words) {
    final String[] separators = {" ", " ", " ", "  ", " ", "\t", "\n", ""};
    final List<String> out = new ArrayList<>();
    out.add("");
    out.add("   ");
    out.add("  ");
    for (int n = 0; n < 400; n++) {
      final StringBuilder s = new StringBuilder();
      if (random.nextInt(5) == 0) {
        s.append(' ');
      }
      final int count = 2 + random.nextInt(4);
      for (int w = 0; w < count; w++) {
        if (w > 0) {
          s.append(separators[random.nextInt(separators.length)]);
        }
        String word = words.get(random.nextInt(words.size()));
        if (random.nextInt(3) == 0) {
          word = mutate(random, word, 1 + random.nextInt(2));
        }
        if (word.length() > 3 && random.nextInt(8) == 0) {
          final int cut = 1 + random.nextInt(word.length() - 1);
          word = word.substring(0, cut) + " " + word.substring(cut);
        }
        s.append(word);
      }
      if (random.nextInt(5) == 0) {
        s.append("  ");
      }
      out.add(s.toString());
    }
    return out;
  }

  /** Phrases with capitals, punctuation, numbers, URLs and e-mail addresses. */
  private static List<String> casedSentences(Random random, List<String> words) {
    final String[] extras = {"12345", "3.14", "+3,14%", "http://example.com/teh", "www.wrold.com",
        "user@example.com", "quikc.com", "(quikc)", "\"wrold\",", "«broen»", "!!!",
        "quikć", "1.2.3", "a.io", "teh-wrold", "x"};
    final List<String> out = new ArrayList<>();
    for (int n = 0; n < 300; n++) {
      final StringBuilder s = new StringBuilder();
      final int count = 1 + random.nextInt(5);
      for (int w = 0; w < count; w++) {
        if (w > 0) {
          s.append(random.nextInt(6) == 0 ? " " : " ");
        }
        if (random.nextInt(5) == 0) {
          s.append(extras[random.nextInt(extras.length)]);
          continue;
        }
        String word = words.get(random.nextInt(words.size()));
        if (random.nextInt(2) == 0) {
          word = mutate(random, word, 1 + random.nextInt(2));
        }
        switch (random.nextInt(4)) {
          case 0 -> word = word.toUpperCase(java.util.Locale.ROOT);
          case 1 -> word = Character.toUpperCase(word.charAt(0)) + word.substring(1);
          default -> {
          }
        }
        if (random.nextInt(6) == 0) {
          word = word + (random.nextBoolean() ? "," : ".");
        }
        s.append(word);
      }
      out.add(s.toString());
    }
    return out;
  }

  private static void writeLookups(PrintWriter out, String dict, SymSpell engine, List<String> terms,
                                   int maxDistance) {
    for (String term : terms) {
      for (Verbosity verbosity : Verbosity.values()) {
        for (int max = 0; max <= maxDistance; max++) {
          out.print("lookup\t" + dict + "\t" + verbosity + "\t" + max + "\t" + escape(term) + "\t");
          final List<SuggestItem> items = engine.lookup(term, verbosity, max);
          for (int i = 0; i < items.size(); i++) {
            out.print((i > 0 ? "|" : "") + item(items.get(i)));
          }
          out.print("\n");
        }
      }
    }
  }

  private static void writeCompound(PrintWriter out, String dict, SymSpell engine,
                                    List<String> sentences, int maxDistance) {
    for (String sentence : sentences) {
      for (int max = 0; max <= maxDistance; max++) {
        final SuggestItem item = engine.lookupCompound(sentence, max).get(0);
        out.print("compound\t" + dict + "\t" + max + "\t" + escape(sentence) + "\t" + item(item) + "\n");
      }
    }
  }

  private static void writeNormalizer(PrintWriter out, SymSpell engine, List<String> sentences,
                                      List<String> cased) {
    final Map<String, SpellCheckingCharSequenceNormalizer> configs = new LinkedHashMap<>();
    configs.put("default", new SpellCheckingCharSequenceNormalizer(engine));
    configs.put("min1", SpellCheckingCharSequenceNormalizer.builder(engine).minTokenLength(1).build());
    configs.put("max1", SpellCheckingCharSequenceNormalizer.builder(engine).maxEditDistance(1).build());
    configs.put("noguards", SpellCheckingCharSequenceNormalizer.builder(engine).minTokenLength(1)
        .skipNumbers(false).skipUrls(false).build());
    configs.put("compound", SpellCheckingCharSequenceNormalizer.builder(engine)
        .mode(SpellCheckingCharSequenceNormalizer.Mode.COMPOUND).build());
    configs.put("compound1", SpellCheckingCharSequenceNormalizer.builder(engine)
        .mode(SpellCheckingCharSequenceNormalizer.Mode.COMPOUND).maxEditDistance(1).build());
    final List<String> inputs = new ArrayList<>(sentences);
    inputs.addAll(cased);
    for (Map.Entry<String, SpellCheckingCharSequenceNormalizer> c : configs.entrySet()) {
      for (String input : inputs) {
        out.print("normalize\t" + c.getKey() + "\t" + escape(input) + "\t"
            + escape(c.getValue().normalize(input).toString()) + "\n");
      }
    }
  }

  private static String item(SuggestItem item) {
    return escape(item.term()) + "," + item.editDistance() + "," + item.frequency();
  }

  /**
   * Writes a backslash, a tab, the separators of this file, controls,
   * White_Space other than U+0020, U+FEFF and supplementary characters as
   * {@code \}{@code u{hex}}; every other character as it is.
   */
  private static String escape(String s) {
    final StringBuilder b = new StringBuilder();
    s.codePoints().forEach(cp -> {
      final boolean plain = cp >= 0x20 && cp != '\\' && cp != '|' && cp != ',' && cp != 0x7F
          && !(cp >= 0x80 && cp <= 0x9F) && (cp == ' ' || !UnicodeWhitespace.isWhitespace(cp))
          && cp != 0xFEFF && cp <= 0xFFFF;
      if (plain) {
        b.appendCodePoint(cp);
      } else {
        b.append("\\u{").append(Integer.toHexString(cp).toUpperCase(java.util.Locale.ROOT)).append('}');
      }
    });
    return b.toString();
  }
}
