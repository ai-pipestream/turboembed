#!/bin/sh
# Regenerates src/snowball/algorithms/*.rs from the Snowball sources. See
# README.md.
#
# Usage: generate.sh [<snowball checkout>]
#
# Without a checkout, Snowball is cloned into a temporary directory. The
# compiler is built at commit PIN with rust-utf16.patch applied; it needs a
# C compiler and make. rustfmt formats the output with the workspace's
# rustfmt.toml.
set -eu

PIN=9a22f0d3f44cda36677829328fe2642750114d57
# SnowballStemmer.ALGORITHM, lower-cased: the .sbl file of each.
LANGS="arabic danish dutch catalan english finnish french german greek hungarian indonesian irish italian norwegian porter portuguese romanian russian spanish swedish turkish"

here=$(cd "$(dirname "$0")" && pwd)
crate=$(dirname "$here")
out="$crate/src/snowball/algorithms"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

if [ $# -gt 0 ]; then
    git -C "$1" worktree add -q --detach "$work/snowball" "$PIN"
    trap 'git -C "$1" worktree remove --force "$work/snowball"; rm -rf "$work"' EXIT
else
    git clone -q https://github.com/snowballstem/snowball.git "$work/snowball"
    git -C "$work/snowball" checkout -q --detach "$PIN"
fi
git -C "$work/snowball" apply "$here/rust-utf16.patch"
make -C "$work/snowball" -s snowball

for lang in $LANGS; do
    "$work/snowball/snowball" "$work/snowball/algorithms/$lang.sbl" -rust -o "$work/$lang"
    {
        echo "//! Generated by the Snowball compiler at commit $PIN from"
        echo "//! algorithms/$lang.sbl, with ../../../snowball/rust-utf16.patch applied."
        echo "//! Do not edit; run snowball/generate.sh."
        # The compiler's own first line names its version, 2.2.0, which the
        # commit is ahead of.
        tail -n +2 "$work/$lang.rs"
    } > "$out/$lang.rs"
done
rustfmt --edition 2024 --config-path "$crate/../../rustfmt.toml" "$out"/*.rs
