//! The Spanish words the number grammar knows, in their folded form
//! (`dieciseis` for `dieciséis`, `vigesimo` for `vigésimo`): the lexer
//! folds accents before it looks a word up.
//!
//! The tables follow the Spanish spell-out of CLDR's rule-based number
//! format (cardinals with their feminine forms, ordinals, and the long
//! scale, where a `billón` is a million millions) and common usage: the
//! apocopated `un`, `veintiún`, `primer` and `tercer`, `setimo` beside
//! `septimo`, the `-avo` denominators, and the abbreviations `dz` and
//! `doz`.

