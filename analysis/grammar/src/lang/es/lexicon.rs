const fn e(word: &'static str, dim: crate::engine::Dim, value: i64, flags: u8) -> Entry {
    Entry { word, dim, value, flags }
}

/// A `FRAC_WORD` that is a noun, `mitad`, which stands alone as a half.
pub(crate) const NOUN: u8 = 1;
/// The hundred that takes no smaller part after it: `cien`.
pub(crate) const CIEN: u8 = 1;

/// Ordinal suffixes carry the last digits they go with, as bits: 1 for a
/// last digit of one, 2 for two, and so on to 512 for nine and 1 << 10
/// for zero; [`ANY_DIGIT`] for the indicators `º` and `ª`, and [`ELEVEN`]
/// and [`TWELVE`] for numbers ending in 11 and 12 (`11mo`, `12vo`).
pub(crate) const ANY_DIGIT: i64 = 0x7ff;
pub(crate) const ELEVEN: i64 = 1 << 11;
pub(crate) const TWELVE: i64 = 1 << 12;

const fn digits(ds: &[u8]) -> i64 {
    let mut bits = 0;
    let mut i = 0;
    while i < ds.len() {
        bits |= if ds[i] == 0 { 1 << 10 } else { 1 << (ds[i] - 1) };
        i += 1;
    }
    bits
}

