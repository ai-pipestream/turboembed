use super::*;

pub(super) const fn r(
    name: &'static str,
    dim: crate::engine::Dim,
    weight: i16,
    items: &'static [Item],
    build: crate::engine::Build,
) -> Rule {
    Rule { name, dim, items, weight, build }
}

