//! Spelled-out English unit extensions for query quantity extraction.

/// Returns a [`turbo_numeric::QuantityExtractor`] accepting both the default
/// abbreviated units and spelled-out English unit words (`kilometers`,
/// `kilograms`, `milliseconds`, etc.).
pub(crate) fn query_quantity_extractor(
    notation: turbo_analysis_layers::NumberNotation,
) -> turbo_numeric::QuantityExtractor {
    const LONG_UNITS: [&str; 57] = [
        "kilometer",
        "kilometers",
        "kilometre",
        "kilometres",
        "meter",
        "meters",
        "metre",
        "metres",
        "centimeter",
        "centimeters",
        "millimeter",
        "millimeters",
        "mile",
        "miles",
        "yard",
        "yards",
        "inch",
        "inches",
        "feet",
        "kilogram",
        "kilograms",
        "gram",
        "grams",
        "milligram",
        "milligrams",
        "ton",
        "tons",
        "liter",
        "liters",
        "milliliter",
        "milliliters",
        "millisecond",
        "milliseconds",
        "microsecond",
        "microseconds",
        "minute",
        "minutes",
        "hour",
        "hours",
        "kilobyte",
        "kilobytes",
        "megabyte",
        "megabytes",
        "gigabyte",
        "gigabytes",
        "terabyte",
        "terabytes",
        "petabyte",
        "petabytes",
        "kilowatt",
        "kilowatts",
        "megawatt",
        "megawatts",
        "calorie",
        "calories",
        "kilocalorie",
        "kilocalories",
    ];
    turbo_numeric::QuantityExtractor::with_units(
        turbo_numeric::DEFAULT_UNITS.iter().chain(LONG_UNITS.iter()).copied(),
        notation,
    )
    .unwrap_or_else(|_| turbo_numeric::QuantityExtractor::new(notation))
}
