"""Generates the mojibake repair's character classes and its test fixture
from ftfy 6.3.1 (Copyright Robyn Speer, Apache-2.0).

ftfy writes its character classes as Python strings of named characters
and runs them through Python regular expressions; this script asks those
expressions which characters they match, so the Rust tables hold exactly
the sets ftfy uses. It also runs ftfy's own fix_encoding over its test
cases to record the text and the explanation the Rust port has to match.

Usage, from the repository root, with an unpacked ftfy 6.3.1 sdist:

    python3 -I analysis/encoding-gen/ftfy.py <ftfy-6.3.1 dir> .

It writes analysis/encoding/src/repair/classes.rs and
analysis/encoding/tests/data/ftfy_cases.tsv. Nothing at build or run time
uses Python.
"""

import json
import os
import re
import sys
import types
import unicodedata

FTFY_DIR, REPO = sys.argv[1], sys.argv[2]

# ftfy's package imports wcwidth for display helpers this script does not
# use; a stub stands in so the package imports without it.
stub = types.ModuleType("wcwidth")
stub.wcwidth = stub.wcswidth = lambda s: 0
sys.modules["wcwidth"] = stub
sys.path.insert(0, FTFY_DIR)

import ftfy  # noqa: E402
from ftfy import badness, chardata  # noqa: E402

ALL = "".join(chr(c) for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF)
CATS = badness.MOJIBAKE_CATEGORIES
CLUES = chardata.UTF8_CLUES

# Every bracket expression of BADNESS_RE and UTF8_DETECTOR_RE that is
# more than a handful of literal characters, written as the regexes write
# them. The Rust matcher names them by these constants.
CLASSES = [
    ("C1", "[{c1}]"),
    ("BAD", "[{bad}]"),
    ("CURRENCY", "[{currency}]"),
    ("NUMERIC", "[{numeric}]"),
    ("START_PUNCT", "[{start_punctuation}]"),
    ("END_PUNCT", "[{end_punctuation}]"),
    ("UPPER_ACCENTED", "[{upper_accented}]"),
    ("LOWER_ACCENTED", "[{lower_accented}]"),
    ("BOX", "[{box}]"),
    ("KAOMOJI", "[{kaomoji}]"),
    ("COMMON_CASED", "[{lower_common}{upper_common}]"),
    ("BEFORE_BAD", "[{bad}{lower_accented}{upper_accented}{box}{start_punctuation}{end_punctuation}{currency}{numeric}{law}]"),
    ("AFTER_BAD", "[{lower_accented}{upper_accented}{box}{start_punctuation}{end_punctuation}{currency}{numeric}{law}]"),
    ("BEFORE_UPPER_ACCENTED", "[{lower_accented}{lower_common}{box}{end_punctuation}{currency}{numeric}]"),
    ("BEFORE_LOWER_ACCENTED", "[{box}{end_punctuation}{currency}{numeric}]"),
    ("BEFORE_CURRENCY", "[{lower_accented}{box}{end_punctuation}]"),
    ("UPPER_ACCENTED_BOX", "[{upper_accented}{box}]"),
    ("NUMERIC_LAW", "[{numeric}{law}]"),
    ("BEFORE_START_NUMERIC", "[{lower_accented}{upper_accented}{box}{currency}{end_punctuation}]"),
    ("BEFORE_END_START", "[{lower_accented}{upper_accented}{currency}{numeric}{box}{law}]"),
    ("CURRENCY_NUMERIC_BOX", "[{currency}{numeric}{box}]"),
    ("START_PUNCT_CURRENCY", "[{start_punctuation}{currency}]"),
    ("BEFORE_BOX", "[{lower_accented}{upper_accented}{currency}{numeric}{start_punctuation}{end_punctuation}{law}]"),
    ("ACCENTED", "[{lower_accented}{upper_accented}]"),
    ("PUNCT", "[{start_punctuation}{end_punctuation}]"),
    ("AFTER_CAP_A_TILDE", "[€œŠš¢£Ÿž\\xa0\\xad®©°·»{start_punctuation}{end_punctuation}\u2013\u2014´]"),
    ("ARABIC_SECOND", "[{common}{currency}{bad}{numeric}{start_punctuation}ŸŠ®°µ»]"),
    ("CYRILLIC_MIDDLE", "[{c1}{bad}{start_punctuation}{end_punctuation}{currency}°µ]"),
    ("BEFORE_CAP_A_CIRCUMFLEX", "[a-z.,?!{end_punctuation}]"),
    ("AFTER_CAP_A_CIRCUMFLEX", "[ {start_punctuation}{end_punctuation}]"),
    ("GREEK_MIDDLE", "[{c1}{bad}{start_punctuation}{end_punctuation}{currency}°]"),
    ("UTF8_FIRST_OF_2", "[{utf8_first_of_2}]"),
    ("UTF8_FIRST_OF_3", "[{utf8_first_of_3}]"),
    ("UTF8_FIRST_OF_4", "[{utf8_first_of_4}]"),
    ("UTF8_CONTINUATION", "[{utf8_continuation}]"),
    ("UTF8_CONTINUATION_STRICT", "[{utf8_continuation_strict}]"),
]
assert len(CLASSES) <= 64

# The class sources must appear in the regexes as written here.
badness_source = badness.BADNESS_RE.pattern
detector_source = chardata.UTF8_DETECTOR_RE.pattern
for name, source in CLASSES:
    expanded = source.format(**CATS, **CLUES)
    if name.startswith("UTF8_"):
        assert expanded in detector_source, name
    elif name not in ("C1", "BAD", "CURRENCY", "NUMERIC", "START_PUNCT", "END_PUNCT", "LOWER_ACCENTED", "BOX", "KAOMOJI"):
        assert expanded in badness_source, name

masks = {}
for bit, (name, source) in enumerate(CLASSES):
    pattern = re.compile(source.format(**CATS, **CLUES))
    for c in pattern.findall(ALL):
        masks[ord(c)] = masks.get(ord(c), 0) | (1 << bit)

out = []
out.append("//! Character classes of ftfy 6.3.1's mojibake heuristics (Copyright Robyn")
out.append("//! Speer, Apache-2.0; see NOTICE), as the sets of characters its regular")
out.append("//! expressions match. Generated by analysis/encoding-gen/ftfy.py from")
out.append("//! ftfy's badness.py and chardata.py; do not edit by hand.")
out.append("")
for bit, (name, source) in enumerate(CLASSES):
    # The dashes are written as escapes, so the doc comment shows which.
    shown = source.replace("\u2013", "\\u{2013}").replace("\u2014", "\\u{2014}")
    out.append("/// `%s`" % shown)
    out.append("pub(crate) const %s: u64 = 1 << %d;" % (name, bit))
out.append("")
out.append("/// Every character in some class, with the classes it is in, by code")
out.append("/// point.")
out.append("#[rustfmt::skip]")
out.append("pub(crate) static CLASSES: [(u32, u64); %d] = [" % len(masks))
for cp in sorted(masks):
    out.append("    (0x%04X, 0x%X)," % (cp, masks[cp]))
out.append("];")
path = os.path.join(REPO, "analysis/encoding/src/repair/classes.rs")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")


def esc(s):
    r = []
    for c in s:
        if c == "\\":
            r.append("\\\\")
        elif c == "\t":
            r.append("\\t")
        elif c == "\n":
            r.append("\\n")
        elif c == "\r":
            r.append("\\r")
        elif unicodedata.category(c) in ("Cc", "Cf", "Co", "Cn", "Zl", "Zp", "Zs") and c != " ":
            r.append("\\u{%X}" % ord(c))
        else:
            r.append(c)
    return "".join(r)


cases = json.load(open(os.path.join(FTFY_DIR, "tests/test_cases.json"), encoding="utf-8"))
rows = []
for case in cases:
    variants = [("", case["original"])]
    # ftfy's own test also runs every passing case with one more layer of
    # UTF-8 read as Latin-1 on top.
    if case["expect"] == "pass":
        variants.append((" (extra layer)", case["original"].encode("utf-8").decode("latin-1")))
    for suffix, original in variants:
        result = ftfy.fix_encoding_and_explain(original)
        plan = ",".join("%s:%s" % (step.action, step.parameter) for step in result.explanation)
        intended = case.get("fixed-encoding", case["fixed"]) if suffix == "" else ""
        rows.append("\t".join([
            esc(case["label"] + suffix), case["expect"] if suffix == "" else "-", esc(original),
            esc(result.text), esc(intended), plan or "-",
        ]))

header = """# ftfy 6.3.1 tests/test_cases.json (Copyright Robyn Speer, Apache-2.0;
# see NOTICE), with what ftfy's own fix_encoding_and_explain returns for
# each. Generated by analysis/encoding-gen/ftfy.py; do not edit by hand.
#
# Columns, tab-separated: label, ftfy's expectation ("pass", "fail", or
# "-" for the extra-layer variant of a passing case), the original text,
# ftfy's fix_encoding output, the output the test file intends
# ("fixed-encoding", else "fixed"; empty for the variants), and ftfy's
# explanation as action:parameter steps ("-" for none). Text escapes:
# \\\\ \\t \\n \\r and \\u{HEX}.
"""
path = os.path.join(REPO, "analysis/encoding/tests/data/ftfy_cases.tsv")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", encoding="utf-8") as f:
    f.write(header + "\n".join(rows) + "\n")
print("classes:", len(masks), "rows:", len(rows))
