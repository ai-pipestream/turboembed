inline bool size_is_known(const turbo_error *, uint32_t size) {
    static const size_t sizes[] = {
        offsetof(turbo_error, field),
        offsetof(turbo_error, message),
        sizeof(turbo_error),
    };
    for (size_t s : sizes) {
        if (s == size) {
            return true;
        }
    }
    return false;
}

