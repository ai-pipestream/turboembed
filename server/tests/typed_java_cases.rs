//! The Rust-produced cases the generated Java client's conformance
//! checks read (issue #1910): the #1907 chained-view fixture documents
//! as document graph bytes, and `Document::map_span` over every span on
//! character boundaries of every view pair, as the Java port of the wire
//! chain must map them. The file is written with `TURBO_UPDATE_FIXTURE`
//! set and checked against the current producer otherwise, so it never
//! goes stale: a graph format or mapping change fails here first.

#[path = "typed_envelope/fixtures.rs"]
mod fixtures;

use std::fmt::Write as _;

use turbo_analysis::export::export;
use turbo_analysis::{Document, Span, ViewId};
use turbo_kserve::results::document::codecs;

use fixtures::fixture_documents;

const CASES_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../clients/java/src/test/resources/mapping-cases.txt");

/// Every span on character boundaries of `text`, the empty ones
/// included, in the order the Java side enumerates them: by start, then
/// by end.
fn all_spans(text: &str) -> Vec<Span> {
    let bounds: Vec<u32> =
        text.char_indices().map(|(i, _)| i as u32).chain(std::iter::once(text.len() as u32)).collect();
    let mut out = Vec::new();
    for (i, &s) in bounds.iter().enumerate() {
        for &e in &bounds[i..] {
            out.push(Span::new(s, e));
        }
    }
    out
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// One case: its name, view count, graph bytes, and for every ordered
/// pair of views the mapped spans in `all_spans` order of the source
/// view's text.
fn render_case(out: &mut String, name: &str, doc: &Document) {
    let graph = export(doc, codecs()).unwrap().to_bytes().unwrap();
    let n = doc.view_count() as u16;
    writeln!(out, "case {name} views {n}").unwrap();
    writeln!(out, "graph {}", hex(&graph)).unwrap();
    for from in 0..n {
        let spans = all_spans(doc.text(ViewId(from)));
        for to in 0..n {
            write!(out, "map {from} {to}").unwrap();
            for &s in &spans {
                let m = doc.map_span(ViewId(from), ViewId(to), s).unwrap();
                write!(out, " {}:{}", m.start, m.end).unwrap();
            }
            out.push('\n');
        }
    }
    out.push_str("end\n");
}

fn render() -> String {
    let mut out = String::new();
    out.push_str("# Generated by server/tests/typed_java_cases.rs (TURBO_UPDATE_FIXTURE=1); do not edit.\n");
    out.push_str("# case <name> views <n> / graph <hex TGRF bytes> / map <from> <to> <start:end>... / end\n");
    for (name, doc) in fixture_documents() {
        render_case(&mut out, name, &doc);
    }
    out
}

#[test]
fn the_java_mapping_cases_are_the_current_producers_output() {
    let want = render();
    if std::env::var_os("TURBO_UPDATE_FIXTURE").is_some() {
        std::fs::write(CASES_PATH, &want).unwrap();
    }
    let have = std::fs::read_to_string(CASES_PATH).unwrap_or_default();
    assert_eq!(
        have, want,
        "clients/java/src/test/resources/mapping-cases.txt is stale; regenerate with TURBO_UPDATE_FIXTURE=1"
    );
}

#[test]
fn the_cases_cover_every_fixture_and_view_pair() {
    let text = render();
    let names: Vec<&str> = text.lines().filter_map(|l| l.strip_prefix("case ")).collect();
    assert_eq!(names.len(), fixture_documents().len());
    for (name, doc) in fixture_documents() {
        let n = doc.view_count();
        assert!(names.iter().any(|c| c.starts_with(&format!("{name} views {n}"))), "{name}");
        let maps =
            text.lines().skip_while(|l| !l.starts_with(&format!("case {name} "))).skip(1).take_while(|l| *l != "end");
        assert_eq!(maps.filter(|l| l.starts_with("map ")).count(), n * n, "{name}: every view pair");
    }
}
