//! No function is written twice inside one crate (#2459). When a large
//! file is split, or a module is renamed and the old one is left behind, a
//! helper ends up in two places with the same body, and a later fix reaches
//! only one of them (#2456).
//!
//! The check reads each crate's `src/` (not its tests, and not generated
//! files), takes every function body of [`MIN_LINES`] code lines or more,
//! and fails when one crate holds the same body twice, in two files or in
//! one (#2518): the same tokens (`rust_lex.rs`), so comments, line breaks
//! and indentation do not count and the contents of a string do. The
//! same method written for two types counts, whatever the types: the
//! shared part moves to a function both call. There is no list of known
//! copies: the last of those the check found when it was written were
//! folded by #2499 and #2506, the shorter ones when the limit came down
//! from eight lines to five by #2530, the ones inside one file by #2518,
//! and a new copy is fixed, not listed.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use crate::rust_lex::{Kind, Token, closing, tokens};

/// Bodies shorter than this are not compared: below it sit the trait
/// methods and one-line wrappers every implementor has to repeat.
pub const MIN_LINES: usize = 5;

/// The index of the `{` that opens the body of the function whose `fn`
/// is at `at`, or `None` for a declaration without one. A brace inside the
/// signature's own brackets (`[u8; { N }]`, `Foo<{ N + 1 }>`) is not it.
fn body_open(tokens: &[Token<'_>], at: usize) -> Option<usize> {
    let mut angles = 0usize;
    let mut i = at + 2;
    while i < tokens.len() {
        let t = &tokens[i];
        if t.is('(') || t.is('[') {
            i = closing(tokens, i);
        } else if t.is('-') && tokens.get(i + 1).is_some_and(|n| n.is('>')) {
            i += 1;
        } else if t.is('<') {
            angles += 1;
        } else if t.is('>') {
            angles = angles.saturating_sub(1);
        } else if t.is('{') && angles > 0 {
            i = closing(tokens, i);
        } else if t.is('{') {
            return Some(i);
        } else if t.is(';') || t.is('}') {
            return None;
        }
        i += 1;
    }
    None
}

/// Every function of `tokens` that has a body: the token of its name,
/// and the tokens of the body from its opening brace to the matching one.
/// Functions written inside another function's body are read too.
pub fn functions<'t, 'a>(tokens: &'t [Token<'a>]) -> Vec<(&'t Token<'a>, &'t [Token<'a>])> {
    let mut out = Vec::new();
    for at in 0..tokens.len().saturating_sub(1) {
        let name = &tokens[at + 1];
        if tokens[at].word("fn")
            && name.kind == Kind::Word
            && let Some(open) = body_open(tokens, at)
        {
            out.push((name, &tokens[open..=closing(tokens, open)]));
        }
    }
    out
}

/// How many lines of a body carry code. Blank lines and lines that hold
/// only a comment have no token; a string over several lines counts once.
pub fn code_lines(body: &[Token<'_>]) -> usize {
    body.iter().map(|t| t.line).collect::<BTreeSet<_>>().len()
}

/// Each body written in two or more places of `files` (path and text,
/// all of one crate), in two files or twice in one, as its first place and
/// every place it is written. A place is `path:line::name`, the line that
/// of the name: two methods of one file can share a name. Two bodies are
/// the same when their tokens are: comments, line breaks and indentation
/// do not count, the contents of a string do.
pub fn shared_bodies(files: &[(&str, &str)]) -> BTreeMap<String, Vec<String>> {
    let read: Vec<(&str, Vec<Token<'_>>)> = files.iter().map(|(path, text)| (*path, tokens(text))).collect();
    let mut by_body: BTreeMap<Vec<&str>, Vec<(&str, u32, &str)>> = BTreeMap::new();
    for (path, tokens) in &read {
        for (name, body) in functions(tokens) {
            if code_lines(body) >= MIN_LINES {
                by_body.entry(body.iter().map(|t| t.text).collect()).or_default().push((path, name.line, name.text));
            }
        }
    }
    let mut out = BTreeMap::new();
    for mut places in by_body.into_values() {
        places.sort();
        if places.len() > 1 {
            let places: Vec<String> =
                places.iter().map(|(path, line, name)| format!("{path}:{line}::{name}")).collect();
            out.insert(places[0].clone(), places);
        }
    }
    out
}

/// A generated file says so in its first lines; a test module is named so.
fn compared(path: &str, text: &str) -> bool {
    let head: String = text.lines().take(3).collect();
    !path.ends_with("tests.rs") && !head.contains("Generated by")
}

/// The shared bodies of every crate in the tree, by `first path::name`.
fn committed(root: &Path) -> (usize, BTreeMap<String, Vec<String>>) {
    let out = std::process::Command::new("git")
        .current_dir(root)
        .args(["ls-files", "-z", "--", "*.rs", "*Cargo.toml"])
        .output()
        .expect("git lists the committed files");
    assert!(out.status.success());
    let listed = String::from_utf8(out.stdout).unwrap();
    let paths: Vec<&str> = listed.split('\0').filter(|s| !s.is_empty()).collect();
    let crates: BTreeSet<&str> = paths.iter().filter_map(|p| p.strip_suffix("/Cargo.toml")).collect();
    // a file belongs to the nearest crate above it, and counts when it is under that crate's src/
    let mut by_crate: BTreeMap<&str, Vec<(&str, String)>> = BTreeMap::new();
    for path in paths.iter().filter(|p| p.ends_with(".rs")) {
        let mut dir = *path;
        while let Some((up, _)) = dir.rsplit_once('/') {
            dir = up;
            if crates.contains(dir) {
                break;
            }
        }
        if !crates.contains(dir) || !path[dir.len()..].starts_with("/src/") {
            continue;
        }
        let text = std::fs::read_to_string(root.join(path)).unwrap_or_else(|e| panic!("{path}: {e}"));
        if compared(path, &text) {
            by_crate.entry(dir).or_default().push((path, text));
        }
    }
    let mut seen = 0;
    let mut out = BTreeMap::new();
    for files in by_crate.values() {
        seen += files.len();
        let files: Vec<(&str, &str)> = files.iter().map(|(p, t)| (*p, t.as_str())).collect();
        out.extend(shared_bodies(&files));
    }
    (seen, out)
}

#[test]
fn no_function_is_written_twice_in_one_crate() {
    let (seen, found) = committed(&crate::common::workspace());
    assert!(seen > 1000, "the source scan is too narrow: {seen} files");
    let fresh: Vec<String> = found.values().map(|places| places.join("\n    = ")).collect();
    assert!(
        fresh.is_empty(),
        "the same body of {MIN_LINES} or more lines is written twice in one crate; keep one and call it:\n  {}",
        fresh.join("\n  ")
    );
}

const BODY: &str = "{\n    let b = 2;\n    let c = 3;\n    b + c\n}";

fn names(source: &str) -> Vec<&str> {
    functions(&tokens(source)).iter().map(|(name, _)| name.text).collect()
}

fn body_text(source: &str, name: &str) -> String {
    let read = tokens(source);
    let found = functions(&read).into_iter().find(|(n, _)| n.text == name).expect("the function is read");
    found.1.iter().map(|t| t.text).collect::<Vec<_>>().join(" ")
}

#[test]
fn functions_are_read_past_strings_characters_and_comments() {
    let text = r##"
        trait T { fn declared(&self) -> [u8; 4]; fn given(&self) -> u8 { 1 } }
        // fn commented() { }
        /* fn blocked() { } /* fn nested() { } */ fn still_blocked() { } */
        const S: &str = "fn quoted() { }";
        fn braces<'a>(s: &'a str) -> usize {
            let open = '{';
            let quote = '\'';
            let text = "}}}";
            let raw = r#"}"}"#;
            fn inner() { }
            s.len() // }
        }
        type Pointer = fn(u8) -> u8;
        fn après() -> usize { let café = 0; café }
    "##;
    assert_eq!(names(text), ["given", "braces", "inner", "après"]);
    assert!(body_text(text, "braces").ends_with("s . len ( ) }"));
    assert_eq!(body_text(text, "après"), "{ let café = 0 ; café }");
}

#[test]
fn source_cut_anywhere_is_read_without_a_panic() {
    // every prefix of awkward source: unclosed strings, comments, brackets and bodies
    let text = "fn café<'a, const N: usize>(s: &'a str) -> [u8; { N }] { let 名 = r#\"}\"#; /* a /* b */ c */ \
                let q = '\\''; let b = b'}'; match s { \"é\" => [0; N], _ => { fn inner() {} [1; N] } } }";
    for (end, _) in text.char_indices() {
        let read = tokens(&text[..end]);
        for (_, body) in functions(&read) {
            assert!(body.first().is_some_and(|t| t.is('{')));
        }
    }
    assert_eq!(names(text), ["café", "inner"]);
}

#[test]
fn a_brace_in_the_signature_is_not_the_body() {
    let text = "fn f<const N: usize>() -> [u8; { N }] { [0; N] }\n\
                fn g(x: Wide<{ 1 + 2 }>) -> Wide<{ 3 }> where Wide<{ 3 }>: Copy { x.grow() }\n\
                fn h<F: Fn() -> u8>(f: F) -> u8 { f() }";
    assert_eq!(body_text(text, "f"), "{ [ 0 ; N ] }");
    assert_eq!(body_text(text, "g"), "{ x . grow ( ) }");
    assert_eq!(body_text(text, "h"), "{ f ( ) }");
}

#[test]
fn the_same_body_in_two_files_is_reported_whatever_its_comments_and_layout() {
    let a = format!("fn first() -> i32 {BODY}\nfn short() -> i32 {{\n    1\n}}\n");
    let places: Vec<String> = vec!["c/src/a.rs:1::first".into(), "c/src/b.rs:2::second".into()];
    let expected = BTreeMap::from([("c/src/a.rs:1::first".to_owned(), places)]);
    for changed in [
        // a comment on a line of its own, a blank line and other indentation
        BODY.replace("    let c = 3;", "        // the third\n\n        let c = 3;"),
        // a comment after the code, and a block comment standing alone
        BODY.replace("let c = 3;", "let c = 3; // the third").replace("    b + c", "    /* the sum */\n    b + c"),
        // a statement broken over two lines
        BODY.replace("let b = 2;", "let b =\n        2;"),
    ] {
        let b = format!("impl X {{\n    pub(crate) fn second(&self) -> i32 {changed}\n}}\n");
        assert_eq!(shared_bodies(&[("c/src/a.rs", &a), ("c/src/b.rs", &b)]), expected, "{changed}");
    }
}

#[test]
fn the_same_body_twice_in_one_file_is_reported() {
    // two functions of one file, alone in the crate and beside another file
    let a = format!("fn first() -> i32 {BODY}\n\nfn again() -> i32 {BODY}\n");
    let places: Vec<String> = vec!["c/src/a.rs:1::first".into(), "c/src/a.rs:7::again".into()];
    let expected = BTreeMap::from([("c/src/a.rs:1::first".to_owned(), places)]);
    assert_eq!(shared_bodies(&[("c/src/a.rs", &a)]), expected);
    let other = "fn unrelated() -> i32 {\n    7\n}\n";
    assert_eq!(shared_bodies(&[("c/src/a.rs", &a), ("c/src/b.rs", other)]), expected);
    // one method written for two types: the name is the same, the line tells them apart
    let twice = format!(
        "impl T for X {{\n    fn sum(&self) -> i32 {BODY}\n}}\nimpl T for Y {{\n    fn sum(&self) -> i32 {BODY}\n}}\n"
    );
    let places: Vec<String> = vec!["c/src/t.rs:2::sum".into(), "c/src/t.rs:9::sum".into()];
    assert_eq!(shared_bodies(&[("c/src/t.rs", &twice)]).into_values().collect::<Vec<_>>(), [places]);
    // a third copy in another file joins the same report
    let third = format!("fn third() -> i32 {BODY}\n");
    let all = shared_bodies(&[("c/src/a.rs", &a), ("c/src/b.rs", &third)]);
    assert_eq!(all["c/src/a.rs:1::first"], ["c/src/a.rs:1::first", "c/src/a.rs:7::again", "c/src/b.rs:1::third"]);
}

#[test]
fn a_changed_line_and_a_short_body_are_not_reported() {
    let a = format!("fn first() -> i32 {BODY}\n");
    let changed = format!("fn other() -> i32 {}\n", BODY.replace("let c = 3;", "let c = 4;"));
    assert!(shared_bodies(&[("c/src/a.rs", &a), ("c/src/b.rs", &changed)]).is_empty());
    assert!(shared_bodies(&[("c/src/a.rs", &format!("{a}{changed}"))]).is_empty());
    assert_eq!(code_lines(&tokens(BODY)), MIN_LINES, "the fixture sits exactly on the limit");
    let shorter = BODY.replace("    let c = 3;\n", "").replace(" + c", "");
    let (x, y) = (format!("fn f() -> i32 {shorter}"), format!("fn g() -> i32 {shorter}"));
    assert!(shared_bodies(&[("c/src/a.rs", &x), ("c/src/b.rs", &y)]).is_empty());
    assert!(shared_bodies(&[("c/src/a.rs", &format!("{x}\n{y}"))]).is_empty());
    // comment lines do not lift a short body over the limit
    let padded = shorter.replace("    let b", "    // one\n    // two\n    let b");
    let (x, y) = (format!("fn f() -> i32 {padded}"), format!("fn g() -> i32 {padded}"));
    assert!(shared_bodies(&[("c/src/a.rs", &x), ("c/src/b.rs", &y)]).is_empty());
    assert!(shared_bodies(&[("c/src/a.rs", &format!("{x}\n{y}"))]).is_empty());
}

#[test]
fn strings_that_differ_only_in_their_spaces_are_different_bodies() {
    let with = |indent: &str| {
        let text = format!("r#\"\n{indent}line\n\"#");
        format!("fn f() -> &'static str {}", BODY.replace("    b + c", &format!("    let _ = b + c;\n    {text}")))
    };
    let (two, four) = (with("  "), with("    "));
    assert!(shared_bodies(&[("c/src/a.rs", &two), ("c/src/b.rs", &four)]).is_empty());
    assert_eq!(shared_bodies(&[("c/src/a.rs", &two), ("c/src/b.rs", &two)]).len(), 1);
}

#[test]
fn generated_files_and_test_modules_are_not_compared() {
    assert!(compared("c/src/a.rs", "//! A module.\nfn f() {}\n"));
    assert!(!compared("c/src/tables/case.rs", "// Generated by turbo-unicode-gen from UnicodeData.txt.\n"));
    assert!(!compared("c/src/x/tests.rs", "use super::*;\n"));
    assert!(!compared("c/src/head/lemmatizer_tests.rs", "use super::*;\n"));
}
